"""Generates docs/SpecVision_AI_Summary.pdf -- a short project summary
with two real, reproducible test-case results (not mockups). Run from
the repo root with the backend venv active:

    backend\\.venv\\Scripts\\python docs\\generate_summary_pdf.py

Source data for the two cases lives in docs/_build/ (generated by a
throwaway offline-mode pipeline run -- see that directory's JSON files
for the full raw response behind every figure quoted in the PDF).
"""
from __future__ import annotations

import json
from pathlib import Path

from fpdf import FPDF

DOCS_DIR = Path(__file__).resolve().parent
BUILD_DIR = DOCS_DIR / "_build"
OUT_PATH = DOCS_DIR / "SpecVision_AI_Summary.pdf"

NAVY = (39, 47, 71)
SLATE = (71, 85, 105)
LIGHT = (241, 245, 249)
GREEN = (5, 122, 85)
AMBER = (146, 90, 10)
RED = (159, 18, 57)

PAGE_W = 210
MARGIN = 18
CONTENT_W = PAGE_W - 2 * MARGIN


class DocPDF(FPDF):
    def header(self):
        if self.page_no() == 1:
            return
        self.set_font("Helvetica", "", 8)
        self.set_text_color(*SLATE)
        self.set_y(10)
        self.cell(0, 5, "SpecVision AI -- Project Summary", align="L")
        self.set_xy(-MARGIN - 20, 10)
        self.cell(20, 5, f"Page {self.page_no()}", align="R")
        self.ln(8)
        self.set_draw_color(220, 224, 230)
        self.line(MARGIN, 18, PAGE_W - MARGIN, 18)
        self.ln(4)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "", 7)
        self.set_text_color(160, 160, 160)
        self.cell(0, 10, "github.com/Arshath015/SpecVision-AI", align="C")

    def h1(self, text):
        self.set_x(MARGIN)
        self.set_font("Helvetica", "B", 15)
        self.set_text_color(*NAVY)
        self.cell(CONTENT_W, 9, text, new_x="LMARGIN", new_y="NEXT")
        self.set_x(MARGIN)
        self.ln(1)

    def h2(self, text):
        self.set_x(MARGIN)
        self.ln(2)
        self.set_x(MARGIN)
        self.set_font("Helvetica", "B", 11.5)
        self.set_text_color(*NAVY)
        self.cell(CONTENT_W, 7, text, new_x="LMARGIN", new_y="NEXT")
        self.set_x(MARGIN)

    def body(self, text, size=9.5, color=(30, 30, 30)):
        self.set_x(MARGIN)
        self.set_font("Helvetica", "", size)
        self.set_text_color(*color)
        self.multi_cell(CONTENT_W, 5, text, new_x="LMARGIN", new_y="NEXT")
        self.set_x(MARGIN)

    def bullet(self, text, size=9.5):
        self.set_x(MARGIN)
        self.set_font("Helvetica", "", size)
        self.set_text_color(30, 30, 30)
        self.cell(5, 5, "-", new_x="RIGHT", new_y="TOP")
        self.set_x(MARGIN + 5)
        self.multi_cell(CONTENT_W - 5, 5, text, new_x="LMARGIN", new_y="NEXT")
        self.set_x(MARGIN)

    def kv_row(self, label, value, label_w=48, conf=None):
        self.set_x(MARGIN)
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(*SLATE)
        self.cell(label_w, 5.5, label, new_x="RIGHT", new_y="TOP")
        self.set_font("Helvetica", "", 9)
        self.set_text_color(20, 20, 20)
        val_w = CONTENT_W - label_w - (18 if conf else 0)
        self.cell(val_w, 5.5, str(value), new_x="RIGHT", new_y="TOP")
        if conf:
            color = {"high": GREEN, "medium": AMBER, "low": RED}.get(conf, SLATE)
            self.set_font("Helvetica", "B", 8)
            self.set_text_color(*color)
            self.cell(18, 5.5, conf.upper(), new_x="RIGHT", new_y="TOP")
        self.set_x(MARGIN)
        self.ln(5.5)

    def flag_box(self, code, severity, message):
        self.set_x(MARGIN)
        color = {"warning": AMBER, "critical": RED, "info": SLATE}.get(severity, SLATE)
        self.set_font("Helvetica", "B", 8.5)
        self.set_text_color(*color)
        self.cell(CONTENT_W, 5, f"[{severity.upper()}] {code}", new_x="LMARGIN", new_y="NEXT")
        self.set_x(MARGIN)
        self.set_font("Helvetica", "", 8.5)
        self.set_text_color(40, 40, 40)
        self.multi_cell(CONTENT_W, 4.6, message, new_x="LMARGIN", new_y="NEXT")
        self.set_x(MARGIN)
        self.ln(1)


def load(name):
    return json.loads((BUILD_DIR / name).read_text(encoding="utf-8"))


def main():
    case_a = load("case_a.json")
    case_b = load("case_b.json")

    pdf = DocPDF(format="A4")
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.set_margins(MARGIN, 14, MARGIN)

    # ---- Cover / intro -----------------------------------------------
    pdf.add_page()
    pdf.ln(6)
    pdf.set_font("Helvetica", "B", 22)
    pdf.set_text_color(*NAVY)
    pdf.cell(0, 12, "SpecVision AI", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 12)
    pdf.set_text_color(*SLATE)
    pdf.cell(0, 8, "AI-Powered Product Specification and Cost Estimation for Custom Jewelry", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(6)
    pdf.set_draw_color(*NAVY)
    pdf.set_line_width(0.6)
    pdf.line(MARGIN, pdf.get_y(), MARGIN + 40, pdf.get_y())
    pdf.ln(6)

    pdf.h2("What this is")
    pdf.body(
        "An ML engineering system for the custom jewelry domain. It takes a short sales brief "
        "(and optionally a reference photo of a ring) and produces: a structured product specification, "
        "a ranked match against a 42-item inventory catalog, a classical computer-vision estimate of "
        "visible gemstones in the photo, an indicative price, and an explicit confidence/review summary. "
        "The core design goal is honesty about uncertainty: every field carries a source (stated by the "
        "user / inferred by the model / unknown) and a confidence level, and the system is built to say "
        "\"unknown\" or \"needs review\" rather than present a guess as a confident fact."
    )

    pdf.h2("What was built")
    pdf.bullet("Backend (FastAPI, Python): LLM-based extraction (Groq, live mode) with a fully functional "
               "deterministic offline fallback -- no API key required to run the whole pipeline.")
    pdf.bullet("Deterministic inventory matching: a weighted attribute-scoring engine (no LLM) that ranks "
               "the catalog, with a documented 0.72 auto-selection threshold below which it explicitly "
               "declines to claim a reliable match.")
    pdf.bullet("Classical computer vision (OpenCV, no paid vision API): Hough-circle + contour hybrid "
               "pipeline that estimates visible gemstone count, with its own confidence assessment and "
               "image-quality warnings.")
    pdf.bullet("Pricing engine: indicative price derived from the matched catalog item plus documented "
               "adjustments, or explicitly \"unavailable\" when there is nothing reliable to price from.")
    pdf.bullet("Confidence & review layer: cross-checks the CV estimate against the brief, runs "
               "deterministic plausibility checks (implausible carat, metal/purity contradictions), and "
               "raises stable, actionable review flags instead of hiding uncertainty.")
    pdf.bullet("React/TypeScript frontend consuming the real API contract (no mocked data), with distinct "
               "live-mode and offline-mode indicators.")
    pdf.bullet("A 16-case labeled evaluation harness using real photographs (not synthetic), a 52-test "
               "automated pytest suite, and a documented failure analysis of the three worst observed "
               "cases with root causes and proposed fixes (EVALUATION.md).")

    pdf.h2("How to run it")
    pdf.body(
        "cd backend && .venv\\Scripts\\Activate.ps1 && uvicorn app.main:app --reload --port 8000\n"
        "cd frontend && npm run dev   (opens at http://localhost:5173)\n\n"
        "Full setup instructions, environment variables, and architecture are in README.md. "
        "Measured evaluation metrics and failure analysis are in EVALUATION.md.",
        size=9,
    )

    # ---- Case A --------------------------------------------------------
    pdf.add_page()
    pdf.h1("Test case 1 -- successful end-to-end match")
    pdf.body(
        'Brief: "A solitaire ring in 18k yellow gold with a round diamond center stone, about 0.45 carats, '
        'tension setting, eight moissanite side stones, band width 1.7mm." (no photo)',
        size=9.5, color=NAVY,
    )
    pdf.body("Mode: offline/demo (deterministic, no API call -- fully reproducible). Run with:\n"
              "python evaluation/runner/run_evaluation.py --mode offline", size=8.5, color=SLATE)
    pdf.ln(2)

    pdf.h2("Extracted specification")
    spec = case_a["specification"]
    pdf.kv_row("Product type", spec["product_type"]["value"], conf=spec["product_type"]["confidence"])
    pdf.kv_row("Design category", spec["design_category"]["value"], conf=spec["design_category"]["confidence"])
    pdf.kv_row("Metal", f'{spec["metal_purity"]["value"]} {spec["metal_color"]["value"]} {spec["metal_type"]["value"]}', conf=spec["metal_type"]["confidence"])
    pdf.kv_row("Setting type", spec["setting_type"]["value"], conf=spec["setting_type"]["confidence"])
    pdf.kv_row("Center stone", f'{spec["center_stone"]["shape"]["value"]} {spec["center_stone"]["gemstone_type"]["value"]}, {spec["center_stone"]["carat"]["value"]}ct', conf=spec["center_stone"]["carat"]["confidence"])
    pdf.kv_row("Side stones", f'{spec["side_stones"]["count_total"]["value"]}x {spec["side_stones"]["gemstone_type"]["value"]}', conf=spec["side_stones"]["count_total"]["confidence"])
    pdf.kv_row("Band width", f'{spec["dimensions"]["band_width_mm"]["value"]}mm', conf=spec["dimensions"]["band_width_mm"]["confidence"])

    pdf.h2("Inventory match")
    sel = case_a["inventory_match"]["selected"]
    pdf.body(
        f'Selected: {sel["product_id"]} -- "{sel["name"]}" -- match score {sel["match_score"]*100:.0f}% '
        f'(threshold: {case_a["inventory_match"]["threshold_used"]*100:.0f}%) -- PASSED, auto-selected.',
        size=9.5,
    )

    pdf.h2("Indicative price")
    price = case_a["price_estimate"]
    pdf.body(
        f'{price["currency"]} {price["indicative_total"]:,.2f} (base catalog price, no adjustments needed -- '
        f'spec was within the matched item\'s carat/side-stone range). Formula: {price["formula_description"]}',
        size=9,
    )

    pdf.h2("Confidence & review")
    cs = case_a["confidence_summary"]
    status_color = {"auto_approved": GREEN, "needs_review": AMBER, "failed": RED}[cs["overall_status"]]
    pdf.set_x(MARGIN)
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(*status_color)
    pdf.cell(CONTENT_W, 6, f'Status: {cs["overall_status"].upper().replace("_", " ")}', new_x="LMARGIN", new_y="NEXT")
    pdf.set_x(MARGIN)
    pdf.body("No review flags were raised -- every stated attribute was extracted correctly and matched "
              "a real catalog item within tolerance.", size=9)

    # ---- Case B --------------------------------------------------------
    pdf.add_page()
    pdf.h1("Test case 2 -- honest reporting of a real CV limitation")
    pdf.body(
        'Brief: "A sterling silver ring with a large oval citrine centerpiece and an open filigree band, '
        'no side stones." (real photo, Wikimedia Commons CC BY-SA, see evaluation/images/PROVENANCE.md)',
        size=9.5, color=NAVY,
    )
    pdf.body("Mode: offline/demo. This exact case is analyzed in depth as \"Failure #1\" in EVALUATION.md.", size=8.5, color=SLATE)
    pdf.ln(2)

    img_w = 85
    pdf.set_x(MARGIN)
    y0 = pdf.get_y()
    pdf.set_font("Helvetica", "B", 8.5)
    pdf.set_text_color(*SLATE)
    pdf.cell(img_w, 5, "Original photo", align="C", new_x="RIGHT", new_y="TOP")
    pdf.set_x(MARGIN + img_w + 6)
    pdf.cell(img_w, 5, "CV detections overlaid (green circles)", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_x(MARGIN)
    pdf.ln(1)
    img_y = pdf.get_y()
    pdf.image(str(BUILD_DIR / "case_b_original.jpg"), x=MARGIN, y=img_y, w=img_w)
    pdf.image(str(BUILD_DIR / "case_b_annotated.png"), x=MARGIN + img_w + 6, y=img_y, w=img_w)
    pdf.set_xy(MARGIN, img_y + img_w * 0.75 + 4)

    pdf.h2("Extracted specification")
    spec = case_b["specification"]
    purity_label = (spec["metal_purity"]["value"] or "").replace("_silver", " sterling silver").replace("_platinum", " platinum")
    pdf.kv_row("Metal", purity_label or spec["metal_type"]["value"], conf=spec["metal_type"]["confidence"])
    pdf.kv_row("Center stone type", spec["center_stone"]["gemstone_type"]["value"] or "Unknown",
               conf=spec["center_stone"]["gemstone_type"]["confidence"])
    pdf.kv_row("Center stone shape", spec["center_stone"]["shape"]["value"], conf=spec["center_stone"]["shape"]["confidence"])
    pdf.kv_row("Side stones", spec["side_stones"]["count_total"]["value"], conf=spec["side_stones"]["count_total"]["confidence"])
    pdf.body(
        '"Citrine" is not in the system\'s controlled gemstone vocabulary, so center_stone_type is '
        'correctly left Unknown rather than guessed -- a deliberate, documented scope limitation, not a crash.',
        size=8.3, color=SLATE,
    )

    pdf.h2("Computer vision result")
    cv = case_b["cv_estimate"]
    pdf.kv_row("Visible components detected", cv["estimated_visible_count"], conf=cv["confidence"])
    pdf.body(
        f'The photo\'s pierced filigree metalwork was mistaken for {cv["estimated_visible_count"]} small '
        f'gemstones by the classical detector, with HIGH self-reported confidence and no image-quality '
        f'warning -- the ring actually has zero side stones. This is a real, known limitation of the '
        f'classical CV baseline (filigree/pierced metalwork resembles a ring of small stones), documented '
        f'in EVALUATION.md as the project\'s #1 worst observed failure, with a proposed fix '
        f'(geometric-regularity check).',
        size=9,
    )

    pdf.h2("Why the system still catches the error")
    pdf.body(
        "Because the brief explicitly states \"no side stones,\" the confidence layer cross-checks the "
        "CV count against the brief and finds a disagreement ratio far above the 40% threshold -- so this "
        "case is correctly flagged for human review despite the CV module's own overconfidence. If the "
        "same photo were paired with a brief that simply didn't mention side-stone count, this cross-check "
        "would not fire -- a limitation stated explicitly in EVALUATION.md, not hidden.",
        size=9,
    )

    pdf.h2("Confidence & review")
    cs = case_b["confidence_summary"]
    status_color = {"auto_approved": GREEN, "needs_review": AMBER, "failed": RED}[cs["overall_status"]]
    pdf.set_x(MARGIN)
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(*status_color)
    pdf.cell(CONTENT_W, 6, f'Status: {cs["overall_status"].upper().replace("_", " ")}', new_x="LMARGIN", new_y="NEXT")
    pdf.set_x(MARGIN)
    pdf.ln(1)
    for flag in cs["review_flags"]:
        pdf.flag_box(flag["code"], flag["severity"], flag["message"])

    # ---- Metrics page ----------------------------------------------------
    pdf.add_page()
    pdf.h1("Measured evaluation results (16 labeled cases)")
    pdf.body(
        "Full methodology, per-field breakdowns, and the three-worst-failure analysis are in EVALUATION.md. "
        "Figures below are read directly from evaluation/results/evaluation_offline.json -- reproducible "
        "with: python evaluation/runner/run_evaluation.py --mode offline",
        size=9,
    )
    pdf.ln(2)
    pdf.h2("Extraction accuracy (offline / deterministic mode)")
    pdf.bullet("Categorical fields (metal type, purity, color, setting, stone type/shape): 92-100% exact-match accuracy "
               "on cases with a known gold value; design_category 71% (documented taxonomy-overlap limitation).")
    pdf.bullet("0 fabricated values across every field where the correct answer was \"unknown.\"")
    pdf.h2("Inventory matching")
    pdf.bullet("Top-1 / Top-3 hit rate: 100% on the one case engineered to match a specific catalog item.")
    pdf.bullet("No-reliable-match handling: 100% correct (8/8 cases engineered to match nothing reliably).")
    pdf.h2("Computer vision")
    pdf.bullet("Mean absolute error: 16.71 stones across 7 real photos -- driven almost entirely by two "
               "explainable, documented failure modes (filigree metalwork and faceted-stone reflections), "
               "not a uniform small error. See EVALUATION.md for the per-image breakdown.")
    pdf.h2("Review behavior")
    pdf.bullet("Precision: 93%  |  Recall: 100%  |  Flag rate: 88% (14/16 cases correctly got at least one actionable flag).")
    pdf.h2("Operational")
    pdf.bullet("52/52 automated tests passing. 16/16 evaluation cases executed successfully, 0 crashes.")
    pdf.bullet("Live-mode run: 15 real Groq API calls, $0.0000 cost (free tier), including one real "
               "HTTP 429 rate-limit recovery and one real malformed-JSON repair -- both handled correctly.")

    pdf.output(str(OUT_PATH))
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
